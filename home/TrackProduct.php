<script>
    $('.Track').click(function(){
        var TrackingText=$('.TrackingText').val();
        if(TrackingText.trim()==""){
            $('.FieldStatus').html("Tracking id field must not be blank").addClass('alert alert-danger');
        }else{
            
            $.ajax({
                url:"getAddress.php",
                method:"post",
                data:{TrackingText:TrackingText},
                beforeSend:function(){
                     $(".Loader").fadeIn(200);
                },
                complete:function(){
                     $(".Loader").fadeOut(200);   
                   
                },
                success:function(data){
                        $('.col-lg-8').html(data);
                }
            })
        }
        
    })
</script>